# Regenerate app/R/layout_tables.R from the lab's original bullseye layouts.
#
# Inputs, in dev/original_layouts/ (exported with write.csv from the R objects the lab's
# plotting code was run with; the node positions were placed by hand in igraph's tkplot):
#   csea_tkcoords.csv  the 53 nodes of the cell-type tree (27 leaves + 26 internal nodes)
#   csea_coords.csv    the 27 hexagon positions actually drawn: ten leaves were nudged by hand
#                      after the tree was laid out, so hexagons and tree ends differ for them
#   csea_edges.csv     the 52 edges;  csea_labels.csv  the label text drawn over each hexagon
#                      ("\n" marks the original line break) and its tissue
#   tsea_tkcoords.csv  the 49 nodes of the tissue tree;  tsea_edges.csv  its 48 edges
#
# Coordinates are converted to the pixel coordinates of the tools' output images (CSEA
# 1500 x 1125, TSEA 1000 x 750, origin top-left) with the transforms below, which were fitted
# to hexagon centres measured in those images (dev/extract_layout.R); the residuals are
# 0.2 px (CSEA, 27 hexagons) and 0.24 px (TSEA, 25 hexagons). The CSEA image was drawn with
# slightly different x and y scales (its device aspect was not 4:3), hence two scale factors.
#
# Usage: Rscript dev/layouts_from_originals.R      (rewrites app/R/layout_tables.R)
src <- "dev/original_layouts"
rd <- function(f) read.csv(file.path(src, f), stringsAsFactors = FALSE)
conv <- list(csea = c(ax = 141.489, bx = 0.75091, ay = 902.061, by = -0.77047),
             tsea = c(ax = 197.08,  bx = 0.6485,  ay = 640.07,  by = -0.6486))
to_img <- function(d, p) data.frame(d[, 1, drop = FALSE], x = round(p[["ax"]] + p[["bx"]] * d$x, 1),
                                    y = round(p[["ay"]] + p[["by"]] * d$y, 1), stringsAsFactors = FALSE)
csea_tree <- to_img(rd("csea_tkcoords.csv"), conv$csea)
csea_hex  <- to_img(rd("csea_coords.csv"), conv$csea)
csea_lab  <- rd("csea_labels.csv"); csea_lab$label <- gsub("\\\\n", "\n", csea_lab$label, fixed = FALSE)
# The label file predates the tool's 7/31/17 fix ("layer 6 neurons and layer 5b neurons were
# swapped in the CSEA plot output", version note on the CSEA page): Ntsr marks layer 6 and
# Glt25d2 layer 5b, as Table 1 and the published image have them. Swap them back here.
i6 <- csea_lab$code == "Ctx.Ntsr"; i5 <- csea_lab$code == "Ctx.glt25d2"
stopifnot(sum(i6) == 1, sum(i5) == 1, grepl("^Layer 5b", csea_lab$label[i6]), grepl("^Layer 6", csea_lab$label[i5]))
csea_lab$label[c(which(i6), which(i5))] <- csea_lab$label[c(which(i5), which(i6))]
csea_hex$label <- csea_lab$label[match(csea_hex$code, csea_lab$code)]
csea_edges <- rd("csea_edges.csv")
tsea_tree <- to_img(rd("tsea_tkcoords.csv"), conv$tsea)
tsea_edges <- rd("tsea_edges.csv")
stopifnot(!anyNA(csea_hex$label), all(c(csea_edges$from, csea_edges$to) %in% csea_tree$node),
          all(c(tsea_edges$from, tsea_edges$to) %in% tsea_tree$node))

fmt <- function(name, df) {
  cols <- vapply(names(df), function(n) {
    v <- df[[n]]
    body <- paste(if (is.character(v)) encodeString(v, quote = "\"") else format(v, nsmall = 1, trim = TRUE), collapse = ", ")
    paste0("  ", n, " = c(", paste(strwrap(body, 100, exdent = 4), collapse = "\n    "), ")")
  }, "")
  paste0(name, " <- data.frame(\n", paste(cols, collapse = ",\n"), ",\n  stringsAsFactors = FALSE\n)\n")
}
out <- c("# Generated by dev/layouts_from_originals.R from the lab's original layouts; do not edit by hand.",
         "# Pixel coordinates of the tools' output images, origin top-left (CSEA 1500 x 1125, TSEA 1000 x 750).",
         "",
         "# CSEA: hexagon positions (with the label drawn above each), the tree's nodes and edges.",
         fmt("CSEA_NODES", csea_hex), fmt("CSEA_TREE_NODES", csea_tree), fmt("CSEA_TREE_EDGES", csea_edges),
         "# TSEA: tree nodes (the 25 tissues are its leaves, the hexagons sit on them) and edges.",
         fmt("TSEA_TREE_NODES", tsea_tree), fmt("TSEA_TREE_EDGES", tsea_edges))
writeLines(out, "app/R/layout_tables.R")
cat("wrote app/R/layout_tables.R:", nrow(csea_hex), "CSEA hexagons,", nrow(csea_tree), "CSEA tree nodes,", nrow(csea_edges), "edges;",
    nrow(tsea_tree), "TSEA tree nodes,", nrow(tsea_edges), "edges\n")
